// Definir el array con las letras
const letras = ['a', 'b', 'c', 'd', 'e'];

// Recorrer el array usando forEach
letras.forEach((letra) => {
  console.log(letra);
});

// Definir la variable numero
let numero2 = 5;

// Iterar hasta que el valor de numero sea 0
while (numero2 > 0) {
  console.log(numero2);
  numero2--; // Decrementa el valor de numero
}
