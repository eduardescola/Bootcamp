// Generar un número aleatorio entre 0 y 1
const numeroAleatorio = Math.random();
console.log(numeroAleatorio); // Muestra un número aleatorio entre 0 y 1

// Redondear Math.PI a 3 decimales
const piRedondeado = Math.PI.toFixed(3);
console.log(piRedondeado); // Muestra: 3.142

// Convertir a número
const piComoNumero = parseFloat(piRedondeado);
console.log(piComoNumero); // Muestra: 3.142
