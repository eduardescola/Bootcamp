// Definir el array con los valores "a", "b", "c", "d", "e"
const letras = ["a", "b", "c", "d", "e"];

// Usar forEach para recorrer el array y mostrar cada elemento
letras.forEach(letra => {
    console.log(letra);  // Muestra cada letra del array
});

// Definir la variable numero
let numero = 5;

// Usar un bucle while para iterar hasta que numero sea 0
while (numero > 0) {
    console.log(numero); // Muestra el valor actual de numero
    numero--; // Decrementa el valor de numero en 1
}
